let posts = [];
let fetchedAt = null;
let usingDemoData = false;
let currentLanguage = localStorage.getItem("sollerAraLanguage") || "ca";
let currentCategory = "all";
let currentSource = "all";
let currentSearch = "";
let sourceStatus = [];

const languageSelect = document.getElementById("languageSelect");
const feed = document.getElementById("feed");
const searchInput = document.getElementById("searchInput");
const sourceSelect = document.getElementById("sourceSelect");
const lastUpdated = document.getElementById("lastUpdated");

function t(key) {
  return translations[currentLanguage][key] ?? translations.ca[key] ?? key;
}

function formatDate(value) {
  if (!value) return "";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return value;
  const locale = currentLanguage === "ca" ? "ca-ES" : currentLanguage === "es" ? "es-ES" : "en-GB";
  return new Intl.DateTimeFormat(locale, { day: "2-digit", month: "short", year: "numeric" }).format(date);
}

function isNowPost(post) {
  if (!post.published_at) return false;

  const publishedAt = new Date(post.published_at).getTime();
  if (Number.isNaN(publishedAt)) return false;

  const ageHours = (Date.now() - publishedAt) / (60 * 60 * 1000);
  if (ageHours < 0) return false;

  if (post.category === "alerts") return ageHours <= 168;
  if (post.category === "services") return ageHours <= 120;
  return ageHours <= 24;
}

function nowPriority(post) {
  const categoryPriority = {
    alerts: 0,
    services: 1,
    agenda: 2,
    news: 3,
    culture: 4,
    sports: 5,
    commerce: 6,
    social: 7
  };
  return categoryPriority[post.category] ?? 9;
}

function iconFor(category) {
  return {
    alerts: "🚨",
    services: "🛠️",
    agenda: "📅",
    culture: "🎭",
    sports: "⚽",
    commerce: "🏪",
    social: "📱",
    news: "📰"
  }[category] || "📰";
}

function applyTranslations() {
  document.documentElement.lang = currentLanguage;
  languageSelect.value = currentLanguage;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = t(element.dataset.i18nPlaceholder);
  });

  populateSourceSelect();
  updateLastUpdated();
  renderFeed();
}

function updateLastUpdated() {
  if (usingDemoData) {
    lastUpdated.textContent = t("feed.demo");
    return;
  }
  if (!fetchedAt) {
    lastUpdated.textContent = t("feed.loading");
    return;
  }
  const date = new Date(fetchedAt);
  const locale = currentLanguage === "ca" ? "ca-ES" : currentLanguage === "es" ? "es-ES" : "en-GB";
  const formatted = new Intl.DateTimeFormat(locale, {
    day: "2-digit",
    month: "short",
    hour: "2-digit",
    minute: "2-digit"
  }).format(date);
  lastUpdated.textContent = `${t("feed.updated")}: ${formatted}`;
}

function populateSourceSelect() {
  const currentValue = currentSource;
  const uniqueSources = [...new Map(
    posts
      .filter((post) => post.source_id && post.source)
      .map((post) => [post.source_id, { id: post.source_id, name: post.source }])
  ).values()].sort((a, b) => a.name.localeCompare(b.name, currentLanguage));

  sourceSelect.innerHTML = `<option value="all">${t("source.all")}</option>`
    + uniqueSources.map((source) => `<option value="${escapeAttribute(source.id)}">${escapeHtml(source.name)}</option>`).join("");

  sourceSelect.value = uniqueSources.some((source) => source.id === currentValue) ? currentValue : "all";
  currentSource = sourceSelect.value;
}


function renderFeed() {
  const normalizedSearch = currentSearch.trim().toLocaleLowerCase(currentLanguage);
  let visiblePosts = posts.filter((post) => {
    const categoryMatches = currentCategory === "all"
      || (currentCategory === "now" ? isNowPost(post) : post.category === currentCategory);
    const sourceMatches = currentSource === "all" || post.source_id === currentSource;
    const relatedText = Array.isArray(post.related_sources) ? post.related_sources.map((item) => `${item.source || ""} ${item.title || ""}`).join(" ") : "";
    const haystack = `${post.title || ""} ${post.summary || ""} ${post.source || ""} ${relatedText}`.toLocaleLowerCase(currentLanguage);
    const searchMatches = !normalizedSearch || haystack.includes(normalizedSearch);
    return categoryMatches && sourceMatches && searchMatches;
  });

  if (currentCategory === "now") {
    visiblePosts = [...visiblePosts].sort((a, b) => {
      const priorityDiff = nowPriority(a) - nowPriority(b);
      if (priorityDiff !== 0) return priorityDiff;
      return new Date(b.published_at).getTime() - new Date(a.published_at).getTime();
    });
  }

  if (!visiblePosts.length) {
    feed.innerHTML = `<div class="empty">${t("empty")}</div>`;
    return;
  }

  feed.innerHTML = visiblePosts.map((post) => {
    const categoryLabel = translations[currentLanguage].categories[post.category] || post.category;
    const safeUrl = post.url || "#";
    const relatedSources = Array.isArray(post.related_sources) ? post.related_sources : [];
    const relatedHtml = relatedSources.length
      ? `<div class="related-sources"><span>${t("card.related")}:</span>${relatedSources.map((item) => `<a href="${escapeAttribute(item.url || "#")}" target="_blank" rel="noopener noreferrer">${escapeHtml(item.source || "")}</a>`).join("")}</div>`
      : "";
    return `
      <article class="card">
        <div class="card-media" aria-hidden="true">${iconFor(post.category)}</div>
        <div class="card-body">
          <div class="meta">
            <span class="source-wrap">${post.source_type === "official" ? '<span class="official-dot" aria-hidden="true"></span>' : ""}<span class="source-name">${escapeHtml(post.source || "")}</span></span>
            <span>${formatDate(post.published_at)}</span>
          </div>
          <span class="badge">${escapeHtml(categoryLabel)}</span>
          <h3>${escapeHtml(post.title || "")}</h3>
          ${post.summary ? `<p>${escapeHtml(post.summary)}</p>` : ""}
          ${relatedHtml}
          <div class="card-actions">
            <a class="origin-link" href="${escapeAttribute(safeUrl)}" target="_blank" rel="noopener noreferrer">${t("card.original")} →</a>
            <button class="muted-button" type="button" data-share-id="${escapeAttribute(post.id || "")}">${t("card.share")}</button>
          </div>
        </div>
      </article>`;
  }).join("");

  document.querySelectorAll("[data-share-id]").forEach((button) => {
    button.addEventListener("click", () => sharePost(button.dataset.shareId));
  });
}

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#039;");
}

function escapeAttribute(value) {
  return escapeHtml(value);
}

async function sharePost(postId) {
  const post = posts.find((item) => item.id === postId);
  if (!post) return;
  const shareData = { title: post.title, text: post.summary, url: post.url || window.location.href };

  if (navigator.share) {
    try { await navigator.share(shareData); } catch (_) {}
  } else if (navigator.clipboard) {
    await navigator.clipboard.writeText(`${post.title}\n${post.url || window.location.href}`);
  }
}

function applyPostsPayload(payload) {
  if (!payload || !Array.isArray(payload.posts)) {
    throw new Error("Invalid posts payload");
  }
  posts = payload.posts;
  fetchedAt = payload.fetched_at || null;
  sourceStatus = Array.isArray(payload.source_status) ? payload.source_status : [];
  usingDemoData = false;
}

async function loadPosts() {
  const embeddedPayload = window.SOLLER_ARA_DATA;

  if (window.location.protocol === "file:" && embeddedPayload) {
    try {
      applyPostsPayload(embeddedPayload);
      populateSourceSelect();
      updateLastUpdated();
      renderFeed();
      return;
    } catch (error) {
      console.warn("No s'han pogut carregar les dades locals", error);
    }
  }

  try {
    const response = await fetch(`data/posts.json?v=${Date.now()}`, { cache: "no-store" });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const payload = await response.json();
    applyPostsPayload(payload);
  } catch (error) {
    console.warn("No s'ha pogut carregar data/posts.json", error);

    if (embeddedPayload) {
      try {
        applyPostsPayload(embeddedPayload);
      } catch (_) {
        posts = demoPosts;
        fetchedAt = null;
        usingDemoData = true;
      }
    } else {
      posts = demoPosts;
      fetchedAt = null;
      usingDemoData = true;
    }
  }

  populateSourceSelect();
  updateLastUpdated();
  renderFeed();
}

sourceSelect.addEventListener("change", (event) => {
  currentSource = event.target.value;
  renderFeed();
});

languageSelect.addEventListener("change", (event) => {
  currentLanguage = event.target.value;
  localStorage.setItem("sollerAraLanguage", currentLanguage);
  applyTranslations();
});

searchInput.addEventListener("input", (event) => {
  currentSearch = event.target.value;
  renderFeed();
});

document.querySelectorAll(".category").forEach((button) => {
  button.addEventListener("click", () => {
    document.querySelectorAll(".category").forEach((item) => item.classList.remove("active"));
    button.classList.add("active");

    if (button.id === "socialNavButton") {
      document.getElementById("officialSocial")?.scrollIntoView({ behavior: "smooth", block: "start" });
      return;
    }

    currentCategory = button.dataset.category;
    renderFeed();
  });
});

applyTranslations();
loadPosts();
